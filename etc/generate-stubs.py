r"""Generate draft stubs from the built package, source annotations, and docstrings.

Run in an environment containing the built extension, for example::

    uv run --no-sync --with pybind11-stubgen==2.5.5 python etc/generate-stubs.py \
        libsemigroups_pybind11.action
    uv run --no-sync --with pybind11-stubgen==2.5.5 python etc/generate-stubs.py \
        libsemigroups_pybind11.sims --output-dir _generate/stubs

The module argument is required. A single stub is printed to stdout by default,
with diagnostics on standard error. Use --output-dir to write files instead.
Package targets include the submodules discovered by pybind11-stubgen and need
--output-dir when generating multiple stubs. Existing files require --force.
Extension targets default to the classes exported by the public package and its
public submodules, together with their typing dependencies. Use --no-public-only
to generate the full extension stub.
Use --strict to stop on pybind11-stubgen diagnostics instead of emitting drafts.
Output is a draft: missing annotations, dynamic dispatch, and C++ conversions
still require review. This script does not install dependencies or add py.typed.
"""

